/** 构建双向同义词映射 */
export function buildSynonymMap(groups = SYNONYM_GROUPS) {
  const map = new Map()
  for (const g of groups) {
    for (const w of g) {
      const key = w
      const set = map.get(key) || new Set()
      for (const o of g) if (o !== w) set.add(o)
      map.set(key, set)
    }
  }
  return map
}

